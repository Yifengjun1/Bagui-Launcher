_pm_cache = {}
_badge_cache = {}


def _load_asset(*parts):
    """读 app/assets 里的 PNG（读不到返回空 QPixmap，调用方自己兜底）"""
    path = assets.asset(*parts)
    if not os.path.isfile(path):
        return QPixmap()
    pm = QPixmap(path)
    return pm if not pm.isNull() else QPixmap()


def icon_pixmap(size=128) -> QPixmap:
    if size not in _pm_cache:
        pm = _load_asset("logo", "app.png")
        if not pm.isNull():
            pm = pm.scaled(size, size, Qt.KeepAspectRatio, Qt.SmoothTransformation)
        else:                                   # 资源缺失 -> 退回内嵌旧图标
            pm = QPixmap()
            pm.loadFromData(base64.b64decode(_ICON_B64), "PNG")
            if not pm.isNull():
                pm = pm.scaled(size, size, Qt.KeepAspectRatio, Qt.SmoothTransformation)
        _pm_cache[size] = pm
    return _pm_cache[size]


def badge_pixmap(size=40) -> QPixmap:
    """顶部状态栏中间的徽标。

    按 2 倍像素生成再回填 devicePixelRatio：100% 屏不会糊，150% 缩放屏也够锐。
    """
    key = int(size)
    if key not in _badge_cache:
        pm = _load_asset("logo", "badge.png")
        if not pm.isNull():
            pm = pm.scaled(key * 2, key * 2, Qt.KeepAspectRatio,
                           Qt.SmoothTransformation)
            pm.setDevicePixelRatio(2.0)
        _badge_cache[key] = pm
    return _badge_cache[key]


def paint_badge(painter, rect, hover=False, pressed=False, scale=0.87,
                glow=True):
    """把状态栏徽标（绿圈黄花）画进 rect。

    标题栏中间、后台悬浮球、安装向导左上角**共用这一个函数**，三处观感一致；
    资源没打进包时退回老的精灵球（`theme.draw_pokeball`），不会留下空白。
    """
    from PySide6.QtCore import QPointF, QRectF
    from PySide6.QtGui import QBrush, QColor, QRadialGradient
    r = QRectF(rect)
    # 0.87 是「徽标 / 可用边长」的基准比：46px 高的按钮正好 40px 徽标
    f = scale * (1.075 if hover else 1.0) * (0.925 if pressed else 1.0)
    size = min(r.width(), r.height()) * f
    pm = badge_pixmap(max(8, int(round(size))))
    if pm.isNull():                       # 只有资源真的缺失才回退
        from . import theme
        theme.draw_pokeball(painter, r, pressed=pressed, hover=hover)
        return
    cx, cy = r.center().x(), r.center().y()
    if hover and glow:
        g = QRadialGradient(QPointF(cx, cy), size * 0.72)
        g.setColorAt(0.0, QColor(255, 236, 176, 54))
        g.setColorAt(1.0, QColor(255, 236, 176, 0))
        painter.setPen(Qt.NoPen)
        painter.setBrush(QBrush(g))
        painter.drawEllipse(QPointF(cx, cy), size * 0.72, size * 0.72)
    painter.drawPixmap(QRectF(cx - size / 2, cy - size / 2, size, size), pm,
                       QRectF(pm.rect()))


def app_icon(size=128) -> QIcon:
    """多尺寸图标（任务栏/标题栏/托盘共用）"""
    ic = QIcon()
    sizes = (16, 24, 32, 48, 64, 128, 256) if size >= 128 else (size,)
    for s in sizes:
        pm = icon_pixmap(s)
        if not pm.isNull():
            ic.addPixmap(pm)
    return ic
